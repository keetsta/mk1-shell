static const char *glyph(char c)
{
    if (c >= 'A' && c <= 'Z')
        c = (char)(c - 'A' + 'a');
    for (unsigned i = 0; i < sizeof FONT / sizeof FONT[0]; i++)
        if (FONT[i].c == c)
            return FONT[i].g;
    return FONT[0].g;
}

char font_check(void)
{
    for (unsigned i = 0; i < sizeof FONT / sizeof FONT[0]; i++) {
        const char *g = FONT[i].g;
        size_t w = strcspn(g, "/");
        if (strlen(g) != 9 * w + 8)
            return FONT[i].c;
        for (int r = 0; r < 9; r++)
            if (strcspn(g + r * (w + 1), "/") != w)
                return FONT[i].c;
    }
    return 0;
}

static void add_col(marquee *m, uint16_t c)
{
    if (m->ncol < MARQUEE_MAX)
        m->col[m->ncol++] = c;
}

void marquee_start(marquee *m, const char *text)
{
    m->ncol = m->pos = 0;
    for (int i = 0; i < 16; i++)
        add_col(m, 0);
    for (const char *t = text; *t; t++) {
        const char *g = glyph(*t);
        int w = (int)(strchr(g, '/') - g);
        for (int x = 0; x < w; x++) {
            uint16_t c = 0;
            for (int r = 0; r < 9; r++)
                if (g[r * (w + 1) + x] == '#')
                    c |= (uint16_t)(1u << r);
            add_col(m, c);
        }
        add_col(m, 0);
    }
    for (int i = 0; i < 16; i++)
        add_col(m, 0);
}

int marquee_step(marquee *m, uint16_t rows[9])
{
    if (m->pos + 16 > m->ncol)
        return 0;
    for (int r = 0; r < 9; r++) {
        uint16_t v = 0;
        for (int x = 0; x < 16; x++)
            if (m->col[m->pos + x] >> r & 1)
                v |= (uint16_t)(0x8000u >> x);
        rows[r] = v;
    }
    m->pos++;
    return 1;
}
