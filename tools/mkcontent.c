/* Builds src/core/content_gen.c from content/:
 *   content/chN.txt   chapter N of the manual (N from 0, chapter 0 stays open)
 *   content/solN.asm  a reference solution of task N; its answer is the key of chapter N
 * Every task in tasks.c needs a solution: the per-sample check bytes come from running it.
 *
 * mkcontent <content dir> <output .c>
 */
#include <errno.h>
#include <limits.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifdef _WIN32
#include <process.h>
#include <windows.h>
#define GETPID _getpid
#else
#include <unistd.h>
#define GETPID getpid
#endif

#include "../src/core/tasks.h"
#include "../src/core/vm.h"

#define MAX_CH 16
#define CHAPTER_MAX 8192

static char *slurp(const char *path, long *len, long limit)
{
    FILE *f = fopen(path, "rb");
    if (!f)
        return NULL;
    if (fseek(f, 0, SEEK_END))
        goto read_error;
    long n = ftell(f);
    if (n < 0 || fseek(f, 0, SEEK_SET))
        goto read_error;
    if (n > limit || (uintmax_t)n >= SIZE_MAX) {
        errno = EFBIG;
        goto read_error;
    }
    char *b = malloc((size_t)n + 1);
    if (!b) {
        errno = ENOMEM;
        goto read_error;
    }
    if (fread(b, 1, (size_t)n, f) != (size_t)n) {
        free(b);
        errno = EIO;
        goto read_error;
    }
    if (fclose(f)) {
        free(b);
        return NULL;
    }
    b[n] = 0;
    *len = n;
    return b;

read_error: {
    int reason = errno;
    fclose(f);
    errno = reason;
    return NULL;
}
}

static int replace_output(const char *temp, const char *path)
{
#ifdef _WIN32
    return MoveFileExA(temp, path, MOVEFILE_REPLACE_EXISTING | MOVEFILE_WRITE_THROUGH) ? 0 : -1;
#else
    return rename(temp, path);
#endif
}

static void bytes(FILE *o, const uint8_t *p, long n)
{
    for (long i = 0; i < n; i++)
        fprintf(o, "%s0x%02x,", i % 16 ? " " : "\n    ", p[i]);
    fprintf(o, "\n");
}

int main(int argc, char **argv)
{
    if (argc != 3) {
        fprintf(stderr, "usage: mkcontent <content dir> <output .c>\n");
        return 2;
    }
    char path[1024], err[96], temp[sizeof path + 32];
    static vm_t vm;
    uint8_t keys[MAX_CH + 1][32], chk[MAX_CH + 1][TASK_MAX_SEGS][4];
    memset(chk, 0, sizeof chk);

    if (N_TASKS > MAX_CH) {
        fprintf(stderr, "too many tasks\n");
        return 1;
    }
    int temp_len = snprintf(temp, sizeof temp, "%s.tmp.%lu", argv[2], (unsigned long)GETPID());
    if (strlen(argv[1]) + sizeof "/sol00.asm" > sizeof path || temp_len < 0 || (size_t)temp_len >= sizeof temp) {
        fprintf(stderr, "content path is too long\n");
        return 1;
    }
    for (int t = 1; t <= N_TASKS; t++) {
        long n;
        snprintf(path, sizeof path, "%s/sol%d.asm", argv[1], t);
        char *src = slurp(path, &n, LONG_MAX);
        if (!src) {
            perror(path);
            return 1;
        }
        int invalid = vm_assemble(&vm, src, err, sizeof err);
        free(src);
        if (invalid) {
            fprintf(stderr, "%s: %s\n", path, err);
            return 1;
        }
        task_result res;
        if (TASKS[t - 1].segs > TASK_MAX_SEGS) {
            fprintf(stderr, "task %d: more than %d segments\n", t, TASK_MAX_SEGS);
            return 1;
        }
        task_run(&TASKS[t - 1], &vm, NULL, chk[t - 1], &res);
        if (res.err[0] || res.passed != res.segs) {
            fprintf(stderr, "%s: %s\n", path, res.err[0] ? res.err : "did not finish");
            return 1;
        }
        task_key(res.hash, keys[t]);
        printf("task %d %-8s %d instructions, %lu cycles\n", t, TASKS[t - 1].name, vm.n, (unsigned long)res.cycles);
    }

    FILE *o = fopen(temp, "wx");
    if (!o) {
        perror(temp);
        return 1;
    }
    fprintf(o, "/* generated by tools/mkcontent.c from content/, do not edit */\n#include \"content.h\"\n");
    int nch = 0;
    for (int chapter = 0; chapter < MAX_CH; chapter++) {
        long n;
        snprintf(path, sizeof path, "%s/ch%d.txt", argv[1], chapter);
        char *txt = slurp(path, &n, CHAPTER_MAX);
        if (!txt) {
            if (errno == ENOENT)
                continue;
            if (errno == EFBIG)
                fprintf(stderr, "%s: longer than %d bytes\n", path, CHAPTER_MAX);
            else
                perror(path);
            goto discard;
        }
        if (chapter != nch) {
            fprintf(stderr, "%s/ch%d.txt: missing before chapter %d\n", argv[1], nch, chapter);
            free(txt);
            goto discard;
        }
        if (nch > N_TASKS) {
            fprintf(stderr, "%s: no task %d to unlock it\n", path, nch);
            free(txt);
            goto discard;
        }
        uint8_t *buf = malloc((size_t)n + 1);
        if (!buf) {
            fprintf(stderr, "could not allocate chapter buffer\n");
            free(txt);
            goto discard;
        }
        if (nch)
            chapter_crypt(keys[nch], (const uint8_t *)txt, buf, (uint32_t)n);
        else
            memcpy(buf, txt, (size_t)n);
        fprintf(o, "\nstatic const uint8_t ch%d[%ld] = {", nch, n);
        bytes(o, buf, n);
        fprintf(o, "};\n");
        printf("chapter %d %ld bytes%s\n", nch, n, nch ? ", encrypted" : "");
        free(buf);
        free(txt);
        nch++;
    }
    if (!nch) {
        fprintf(stderr, "%s/ch0.txt: missing\n", argv[1]);
        goto discard;
    }
    fprintf(o, "\nconst content_chapter CONTENT_CHAPTERS[] = {\n");
    for (int k = 0; k < nch; k++)
        fprintf(o, "    {ch%d, sizeof ch%d, %d},\n", k, k, k > 0);
    fprintf(o, "};\nconst int CONTENT_N_CHAPTERS = %d;\n", nch);
    fprintf(o, "\nconst uint8_t CONTENT_CHK[][TASK_MAX_SEGS][4] = {\n");
    for (int t = 0; t < N_TASKS; t++) {
        fprintf(o, "    {");
        for (int s = 0; s < TASKS[t].segs; s++)
            fprintf(o, "%s{0x%02x, 0x%02x, 0x%02x, 0x%02x}", s ? ", " : "", chk[t][s][0], chk[t][s][1], chk[t][s][2],
                    chk[t][s][3]);
        fprintf(o, "},\n");
    }
    fprintf(o, "};\nconst int CONTENT_N_TASKS = %d;\n", N_TASKS);
    int failed = ferror(o);
    if (fclose(o))
        failed = 1;
    if (!failed && !replace_output(temp, argv[2]))
        return 0;
    fprintf(stderr, "could not write %s\n", argv[2]);
    remove(temp);
    return 1;

discard:
    fclose(o);
    remove(temp);
    return 1;
}
